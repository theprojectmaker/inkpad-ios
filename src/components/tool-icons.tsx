const parsed = new Map<string, ReturnType<typeof Skia.Path.MakeFromSVGString>>();
function pathOf(name: string) {
  if (!parsed.has(name)) parsed.set(name, Skia.Path.MakeFromSVGString(TOOL_ICONS[name] ?? ''));
  return parsed.get(name)!;
}

export const ToolIcon = memo(function ToolIcon({ name, size = 20, color = '#3B4252', weight = 1.6 }: { name: string; size?: number; color?: string; weight?: number }) {
  const path = pathOf(name);
  const k = size / 24;
  const transform = useMemo(() => [{ scale: k }], [k]);
  if (!path) return <View style={{ width: size, height: size }} />;
  return (
    <Canvas style={{ width: size, height: size }} pointerEvents="none">
      <Path path={path} style="stroke" strokeWidth={weight} strokeCap="round" strokeJoin="round" color={color} transform={transform} />
    </Canvas>
  );
});
